"""Paired differences between policies, with a 95% interval, from comparison.csv.

Run by hand after `scripts/compare_policies.py`:

    PYTHONPATH=. uv run python scripts/paired_statistics.py

Every policy in a cell ran on the same seeds, so the same failures arrived at the
same times. The spread between seeds is far larger than the gap between policies,
so a difference of cell means says little; the difference *per seed* removes the
shared part. This writes, per cell and per pair of policies, the mean paired
difference, its 95% t-interval and how many seeds went each way. An interval that
contains zero is a difference the data cannot tell from noise.

Standard library only: the t quantile is tabulated below for the degrees of
freedom a run can have.
"""

from __future__ import annotations

import csv
import math
import sys
from collections import defaultdict
from pathlib import Path
from statistics import mean, stdev

RESULTS = Path("docs/results")

# Two-sided 95% critical values of Student's t, by degrees of freedom.
_T975 = {
    1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365, 8: 2.306,
    9: 2.262, 10: 2.228, 11: 2.201, 12: 2.179, 13: 2.160, 14: 2.145, 15: 2.131,
    16: 2.120, 17: 2.110, 18: 2.101, 19: 2.093, 20: 2.086, 24: 2.064, 29: 2.045,
    39: 2.023, 49: 2.010, 99: 1.984,
}  # fmt: skip

PAIRS = (("3D", "3A"), ("3D", "3C"), ("3C", "3A"), ("3B", "3A"))
MEASURES = (("units_lost", "units lost"), ("mean_response_minutes", "mean response (min)"))


def t975(df: int) -> float:
    """The critical value for `df`, or the next smaller tabulated one (wider)."""
    return _T975[max(key for key in _T975 if key <= df)]


def interval(differences: list[float]) -> tuple[float, float, float]:
    """Mean, and the 95% t-interval's low and high end."""
    centre = mean(differences)
    if len(differences) < 2:
        return centre, math.nan, math.nan
    half = t975(len(differences) - 1) * stdev(differences) / math.sqrt(len(differences))
    return centre, centre - half, centre + half


def _key(policy: str) -> str:
    return policy.split()[0]


def load(path: Path) -> dict[tuple[str, str], dict[str, dict[int, dict[str, float]]]]:
    """cell (buffer, multiplier) -> policy code -> seed -> measures."""
    cells: dict[tuple[str, str], dict[str, dict[int, dict[str, float]]]] = defaultdict(
        lambda: defaultdict(dict)
    )
    with path.open(newline="") as handle:
        for row in csv.DictReader(handle):
            cell = (row["buffer_units"] or "as configured", row["arrival_multiplier"])
            cells[cell][_key(row["policy"])][int(row["seed"])] = {
                name: float(row[name]) if row[name] else math.nan for name, _ in MEASURES
            }
    return cells


def _buffer_order(buffer: str) -> float:
    return -1.0 if buffer == "as configured" else float(buffer)


def write(cells: dict[tuple[str, str], dict[str, dict[int, dict[str, float]]]], out: Path) -> None:
    lines = [
        "# Paired differences between policies",
        "",
        "**Generated by `scripts/paired_statistics.py` from `comparison.csv`. "
        "Do not edit by hand.**",
        "",
        "Each figure is the mean over seeds of (first policy - second policy) on the "
        "same seed, with its 95% t-interval. Negative means the first policy lost "
        "fewer units or responded sooner. **An interval containing zero is a "
        "difference these runs cannot tell from noise.** `better / worse` counts "
        "the seeds on which the first policy was lower / higher.",
        "",
    ]
    pooled: dict[tuple[str, str, str], list[float]] = defaultdict(list)
    for measure, label in MEASURES:
        lines += [f"## {label}", ""]
        header = "| multiplier | buffer | " + " | ".join(f"{a} - {b}" for a, b in PAIRS) + " |"
        lines += [header, "|---|---|" + "---|" * len(PAIRS)]
        for cell in sorted(cells, key=lambda c: (float(c[1]), _buffer_order(c[0]))):
            policies = cells[cell]
            entries = []
            for first, second in PAIRS:
                seeds = sorted(set(policies[first]) & set(policies[second]))
                differences = [
                    policies[first][seed][measure] - policies[second][seed][measure]
                    for seed in seeds
                ]
                pooled[(measure, first, second)] += differences
                centre, low, high = interval(differences)
                better = sum(d < 0 for d in differences)
                worse = sum(d > 0 for d in differences)
                mark = "" if low <= 0 <= high else " **\\***"
                entries.append(f"{centre:+.1f} [{low:+.1f}, {high:+.1f}]{mark} ({better}/{worse})")
            buffer = cell[0] if cell[0] == "as configured" else f"{cell[0]} units"
            lines.append(f"| {cell[1]} | {buffer} | " + " | ".join(entries) + " |")
        lines.append("")
    lines += [
        "\\* the interval excludes zero.",
        "",
        "## Over every cell",
        "",
        "Cells are not independent (the same seeds run in each), so this interval is "
        "optimistic; it answers only whether the direction is consistent.",
        "",
        "| measure | pair | mean difference | 95% interval | better / worse |",
        "|---|---|---:|---|---|",
    ]
    for (measure, first, second), differences in pooled.items():
        centre, low, high = interval(differences)
        label = dict(MEASURES)[measure]
        better = sum(d < 0 for d in differences)
        worse = sum(d > 0 for d in differences)
        lines.append(
            f"| {label} | {first} - {second} | {centre:+.1f} | "
            f"[{low:+.1f}, {high:+.1f}] | {better} / {worse} |"
        )
    out.write_text("\n".join(lines) + "\n")


def main() -> int:
    cells = load(RESULTS / "comparison.csv")
    out = RESULTS / "comparison-statistics.md"
    write(cells, out)
    print(f"{len(cells)} cells -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
