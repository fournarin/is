"""Calibrate the "give or take" a forecast prints, and check it on held-out seeds.

Run by hand:

    PYTHONPATH=. uv run python scripts/calibrate_eta.py

The interval a forecast carries from the fit is one standard error of the slope
(ADR-043). It gates whether a forecast is raised, and it is right for that. As
what a technician reads it is overconfident: it ignores the intercept, the
correlation between successive readings, and the bias of a straight line through
a curve, and on the synthetic channels it held the true crossing 18-48% of the
time. ADR-106 prints the wider of it and an interval learned from errors that
have actually happened.

**Method (split conformal, by horizon).** On the calibration seeds, for each
horizon band, the 80th percentile of |error| / lead time gives a fraction; the
printed half-width is that fraction of the lead time. Held-out seeds are then
measured once. The bands are those `measure_prediction.py` reports.

**The fractions are properties of the synthetic curves**, not of the plant. A
plant recalibrates by running this over its own closed forecasts, which is the
data ADR-020 said would one day replace these.

Writes `docs/results/eta-calibration.md` and prints the YAML for `policy.yaml`.
"""

from __future__ import annotations

import math
import sys
from datetime import timedelta
from pathlib import Path

from pdm.signals import LINE_A_TWELVE_HOURS
from pdm.triggers.domain import printed_interval
from scripts.measure_prediction import BUCKETS, Measured, measure

CALIBRATION = tuple(range(10))
HELD_OUT = (20260813, *range(10, 20))
TARGET = 0.8
OUT = Path("docs/results/eta-calibration.md")


def _pool(seeds: tuple[int, ...]) -> Measured:
    pooled: Measured = {}
    for seed in seeds:
        for bucket, rows in measure(LINE_A_TWELVE_HOURS, seed=seed).items():
            if bucket != "never crosses":
                pooled.setdefault(bucket, []).extend(rows)
    return pooled


def _quantile(values: list[float], share: float) -> float:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, math.ceil(share * len(ordered)) - 1)]


def main() -> int:
    calibration, held_out = _pool(CALIBRATION), _pool(HELD_OUT)
    bands: list[tuple[float, float]] = []
    for name, _, high in BUCKETS:
        rows = calibration.get(name, [])
        if not rows:
            continue
        ratios = [abs(error) / lead for error, _, _, lead, _, _ in rows if lead > 0]
        bands.append((min(high.total_seconds() / 3600.0, 1e6), round(_quantile(ratios, TARGET), 3)))

    lines = [
        "# How far to trust a printed ETA",
        "",
        "**Generated by `scripts/calibrate_eta.py`. Do not edit by hand.**",
        "",
        f"Scenario `{LINE_A_TWELVE_HOURS.name}`. Fractions learned on seeds "
        f"{CALIBRATION[0]}-{CALIBRATION[-1]}, coverage measured once on seeds "
        f"{', '.join(str(seed) for seed in HELD_OUT[:2])}...{HELD_OUT[-1]} "
        f"({len(HELD_OUT)} seeds). Target {TARGET:.0%}.",
        "",
        "| horizon | fraction of lead time | held-out n | slope interval covers | "
        "calibrated interval covers | median printed ± before | after |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, _, _ in BUCKETS:
        rows = held_out.get(name, [])
        if not rows:
            continue
        before = [w for _, _, w, _, _, _ in rows]
        after = [
            printed_interval(timedelta(minutes=w), timedelta(minutes=lead), bands).total_seconds()
            / 60.0
            for _, _, w, lead, _, _ in rows
        ]
        covered_before = sum(abs(e) <= w for (e, *_), w in zip(rows, before, strict=True))
        covered_after = sum(abs(e) <= w for (e, *_), w in zip(rows, after, strict=True))
        fraction = next(f for below, f in bands if below >= (_upper(name)))
        lines.append(
            f"| {name} | {fraction:.3f} | {len(rows)} | {covered_before / len(rows):.0%} | "
            f"**{covered_after / len(rows):.0%}** | {_quantile(before, 0.5):.1f} min | "
            f"{_quantile(after, 0.5):.1f} min |"
        )
    yaml = ["    eta_error:"] + [
        f"      - {{ahead_below_hours: {below:g}, fraction: {fraction}}}"
        for below, fraction in bands
    ]
    lines += [
        "",
        "For `config/policy.yaml`, under `triggers.trend`:",
        "",
        "```yaml",
        *yaml,
        "```",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


def _upper(name: str) -> float:
    high = next(high for bucket, _, high in BUCKETS if bucket == name)
    return min(high.total_seconds() / 3600.0, 1e6)


if __name__ == "__main__":
    sys.exit(main())
