"""How long one dispatch round takes as the queue grows.

Run by hand:

    PYTHONPATH=. uv run python scripts/measure_round_time.py

A round runs every `dispatch.round_seconds` (300 s) and CP-SAT is given
`dispatch.solver_seconds` (5 s). This times `dispatch()` (3C) and `schedule()`
(3D) on queues of 10, 50 and 200 open orders across the line's four machines,
with 3 and 8 technicians, median of 5 runs. Wall-clock time on this machine: it
says whether a round fits its cadence, not how fast another machine is.
"""

from __future__ import annotations

import sys
import time
from datetime import UTC, datetime, timedelta
from pathlib import Path
from statistics import median

from pdm.contracts import (
    FindingRef,
    MachineId,
    Severity,
    SkillId,
    Technician,
    UserId,
    WorkOrder,
    WorkOrderOrigin,
)
from pdm.dispatch.domain import Queued, dispatch
from pdm.dispatch.solver import schedule
from pdm.platform.config import load_config

NOW = datetime(2026, 3, 3, 8, 0, tzinfo=UTC)
MACHINES = ("MC-001", "MC-004", "MC-012", "MC-018")
SEVERITIES = (Severity.LOW, Severity.MEDIUM, Severity.HIGH, Severity.CRITICAL)
SKILLS = ("robot_mechanical", "electrical")
OUT = Path("docs/results/round-time.md")


def _queue(count: int) -> list[Queued]:
    return [
        Queued(
            ref=f"WO-{index:04d}",
            order=WorkOrder(
                origin=WorkOrderOrigin.CONDITION,
                finding_ref=FindingRef(f"F-{index}"),
                machine_id=MachineId(MACHINES[index % len(MACHINES)]),
                severity=SEVERITIES[index % len(SEVERITIES)],
                estimated_minutes=30 + 15 * (index % 5),
                required_skill=SkillId(SKILLS[index % len(SKILLS)]),
                reason="timing",
            ),
            created_at=NOW - timedelta(minutes=index),
        )
        for index in range(count)
    ]


def main() -> int:
    config = load_config(Path("config"))
    lines = [
        "# How long a dispatch round takes",
        "",
        "**Generated by `scripts/measure_round_time.py`. Do not edit by hand.**",
        "",
        f"Median of 5 runs, seconds. Cadence {config.policy.dispatch.round_seconds} s; "
        f"CP-SAT limit {config.policy.dispatch.solver_seconds} s.",
        "",
        "| open orders | technicians | 3C `dispatch()` | 3D `schedule()` |",
        "|---:|---:|---:|---:|",
    ]
    for count in (10, 50, 200):
        for people in (3, 8):
            technicians = [
                Technician(user=UserId(f"t{n}"), skills=frozenset(SkillId(s) for s in SKILLS))
                for n in range(people)
            ]
            roster = [(person.user, 480) for person in technicians]
            timings: dict[str, list[float]] = {"3C": [], "3D": []}
            for _ in range(5):
                for name, function in (("3C", dispatch), ("3D", schedule)):
                    started = time.perf_counter()
                    function(
                        _queue(count),
                        technicians=technicians,
                        assignments=roster,
                        config=config,
                        now=NOW,
                    )
                    timings[name].append(time.perf_counter() - started)
            greedy, planned = median(timings["3C"]), median(timings["3D"])
            lines.append(f"| {count} | {people} | {greedy:.3f} | {planned:.3f} |")
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
