"""SQL for the work order table. No business logic, no connections opened here.

Every function takes a connection first (ADR-031), so that issuing an order and
whatever prompted it - a Finding being raised, a PM task falling due - commit
together (ADR-017).

**Nothing here updates `playbook_snapshot`.** The trigger in migration 0006 would
refuse it, which is the point: the column is the only evidence of what a job that
closed a year ago instructed, and this module is not the last writer that will
ever exist (invariant 2, ADR-018).
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from psycopg import Connection
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb

from pdm.contracts import (
    Assignee,
    FindingRef,
    MachineId,
    PlaybookStep,
    WorkOrder,
    WorkOrderStatus,
    WorkOutcome,
    WorkSegment,
)

# `actual_minutes` is absent on purpose: it is the sum of the segments, and a
# stored copy could disagree with them (ADR-025).
_COLUMNS = """
    origin, finding_ref, pm_task_ref, machine_id, severity, finding_kind, eta,
    eta_confidence, playbook_ref, playbook_snapshot, snapshot_approved_by,
    snapshot_approved_at, playbook_warning, estimated_minutes, required_skill,
    required_technicians, estimate_is_fallback, reason, priority_score,
    priority_reason, status, assignees, work_segments, handover_note,
    blocked_minutes, blocked_reason, outcome, technician_feedback
"""

OPEN_STATUSES = ("queued", "assigned", "in_progress", "handed_over")


def _to_order(row: dict[str, Any]) -> WorkOrder:
    row.pop("work_order_ref", None)
    row.pop("created_at", None)
    row.pop("closed_at", None)
    row["playbook_snapshot"] = tuple(
        PlaybookStep.model_validate(step) for step in row["playbook_snapshot"]
    )
    row["assignees"] = tuple(Assignee.model_validate(one) for one in row["assignees"])
    row["work_segments"] = tuple(WorkSegment.model_validate(one) for one in row["work_segments"])
    row["blocked_reason"] = tuple(row["blocked_reason"])
    return WorkOrder.model_validate(row)


def issue(conn: Connection[Any], order: WorkOrder, *, now: datetime) -> str:
    """Write a new order and return the ticket number the sequence gave it.

    The reference is generated by the database rather than built from the machine
    and the time: two orders for one machine inside a minute is unlikely and not
    impossible, and slice 3.0's lesson was what "unlikely" is worth in a primary
    key.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            INSERT INTO work_order ({_COLUMNS}, created_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                    %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING work_order_ref
            """,
            (
                order.origin.value,
                order.finding_ref,
                order.pm_task_ref,
                order.machine_id,
                order.severity.value,
                order.finding_kind.value if order.finding_kind else None,
                order.eta,
                order.eta_confidence,
                order.playbook_ref,
                Jsonb([step.model_dump(mode="json") for step in order.playbook_snapshot]),
                order.snapshot_approved_by,
                order.snapshot_approved_at,
                order.playbook_warning,
                order.estimated_minutes,
                order.required_skill,
                order.required_technicians,
                order.estimate_is_fallback,
                order.reason,
                order.priority_score,
                order.priority_reason,
                order.status.value,
                Jsonb([one.model_dump(mode="json") for one in order.assignees]),
                Jsonb([one.model_dump(mode="json") for one in order.work_segments]),
                order.handover_note,
                order.blocked_minutes,
                [reason.value for reason in order.blocked_reason],
                order.outcome.value if order.outcome else None,
                order.technician_feedback,
                now,
            ),
        )
        row = cur.fetchone()
    assert row is not None
    return str(row["work_order_ref"])


def get(conn: Connection[Any], work_order_ref: str) -> WorkOrder | None:
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"SELECT {_COLUMNS} FROM work_order WHERE work_order_ref = %s",
            (work_order_ref,),
        )
        row = cur.fetchone()
    return _to_order(row) if row else None


def open_orders(conn: Connection[Any]) -> list[tuple[str, WorkOrder]]:
    """Everything the dispatch tick has to consider, oldest first.

    **No limit, and that is deliberate.** `load_ratio` is a sum over the whole
    queue (design.md 13.2), so a page of it is not a smaller version of the
    answer - it is a shift that reads emptier than it is, and the gate then
    releases *more* work. A truncation that made the queue look manageable would
    do it by hiding the newest orders, including a critical one raised minutes
    ago.

    The bound is the plant's own: open work orders are jobs somebody has to do,
    and a queue long enough for this to matter is a queue that is itself the
    problem to report.

    Ordered by age rather than by severity: ranking is the scheduler's job, and a
    repository that pre-sorted by one term of the score would be quietly deciding
    part of it.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        # The status list is written out rather than passed as an array so the
        # planner can match the partial index in migration 0006. `= ANY($1)`
        # against a generic plan cannot.
        cur.execute(
            f"""
            SELECT work_order_ref, {_COLUMNS} FROM work_order
             WHERE status IN ('queued', 'assigned', 'in_progress', 'handed_over')
             ORDER BY created_at, work_order_ref
            """
        )
        rows = cur.fetchall()
    return [(str(row["work_order_ref"]), _to_order(dict(row))) for row in rows]


def for_finding(conn: Connection[Any], finding_ref: FindingRef) -> list[tuple[str, WorkOrder]]:
    """What this Finding produced. The trace-back direction (ADR-030)."""
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT work_order_ref, {_COLUMNS} FROM work_order
             WHERE finding_ref = %s ORDER BY created_at
            """,
            (finding_ref,),
        )
        rows = cur.fetchall()
    return [(str(row["work_order_ref"]), _to_order(dict(row))) for row in rows]


def open_for_machine(conn: Connection[Any], machine_id: MachineId) -> list[str]:
    """Open tickets on one machine, for the caller deciding whether to raise
    another. Cheap deliberately: only the references, because the question is
    "is there one" rather than "what does it say"."""
    with conn.cursor() as cur:
        cur.execute(
            "SELECT work_order_ref FROM work_order "
            "WHERE machine_id = %s AND status = ANY(%s) ORDER BY created_at",
            (machine_id, list(OPEN_STATUSES)),
        )
        return [str(row[0]) for row in cur.fetchall()]


class CannotCloseThisWay(Exception):
    """`set_status` was asked to close an order. `close` is the way.

    Closing needs an outcome - the database refuses a closed row without one -
    so a `set_status(CLOSED)` would abort the caller's whole transaction on a
    CHECK constraint rather than doing what it looked like it would do.
    """


def set_status(
    conn: Connection[Any],
    work_order_ref: str,
    *,
    status: WorkOrderStatus,
    handover_note: str | None = None,
) -> bool:
    """Move an order between its open states. Never touches the snapshot.

    Not for closing: an order that has ended has to say how (ADR-022's
    "no problem found" is one of the answers, and the only false-alarm signal
    the system will ever get), and the constraint enforcing that would fail here
    with a message about a CHECK rather than about what the caller forgot.
    """
    if status in (WorkOrderStatus.CLOSED, WorkOrderStatus.CANCELLED):
        raise CannotCloseThisWay(
            f"{status.value} needs an outcome and a time; use close() (ADR-022)"
        )
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET status = %s, handover_note = COALESCE(%s, handover_note)
             WHERE work_order_ref = %s
            """,
            (status.value, handover_note, work_order_ref),
        )
        return cur.rowcount == 1


def close(
    conn: Connection[Any],
    work_order_ref: str,
    *,
    status: WorkOrderStatus,
    outcome: WorkOutcome,
    now: datetime,
    technician_feedback: str | None = None,
) -> bool:
    """End an order, with how it ended and when.

    `closed_at` comes from the clock the caller passes, never `now()`: a
    compressed demo would otherwise stamp real time on a job whose segments are
    simulated (ADR-028).
    """
    if status not in (WorkOrderStatus.CLOSED, WorkOrderStatus.CANCELLED):
        raise ValueError(f"{status.value} is not an ending; use set_status()")
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET status = %s, outcome = %s, closed_at = %s,
                   technician_feedback = COALESCE(%s, technician_feedback)
             WHERE work_order_ref = %s
            """,
            (status.value, outcome.value, now, technician_feedback, work_order_ref),
        )
        return cur.rowcount == 1
