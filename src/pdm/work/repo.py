# `actual_minutes` is absent on purpose: it is the sum of the segments, and a
# stored copy could disagree with them (ADR-025).
_COLUMNS = """
    origin, finding_ref, pm_task_ref, machine_id, severity, finding_kind, eta,
    eta_confidence, playbook_ref, playbook_snapshot, snapshot_approved_by,
    snapshot_approved_at, playbook_warning, estimated_minutes, required_skill,
    required_technicians, estimate_is_fallback, reason, priority_score,
    priority_reason, status, assignees, work_segments, handover_note,
    blocked_minutes, blocked_reason, outcome, technician_feedback, reported_by
"""

OPEN_STATUSES = ("queued", "proposed", "assigned", "in_progress", "handed_over")

# The same columns, qualified, for the one query that joins `finding` - which
# carries a machine_id, a severity, an eta and a status of its own. Derived from
# the list above rather than written out again, so a column added there cannot be
# missing here and read back as a default.
_COLUMNS_FOR_JOIN = ", ".join(f"o.{name.strip()}" for name in _COLUMNS.split(","))


def _to_order(row: dict[str, Any]) -> WorkOrder:
    row.pop("work_order_ref", None)
    row.pop("created_at", None)
    row.pop("closed_at", None)
    row["playbook_snapshot"] = tuple(
        PlaybookStep.model_validate(step) for step in row["playbook_snapshot"]
    )
    row["assignees"] = tuple(Assignee.model_validate(one) for one in row["assignees"])
    row["work_segments"] = tuple(WorkSegment.model_validate(one) for one in row["work_segments"])
    row["blocked_reason"] = tuple(row["blocked_reason"])
    return WorkOrder.model_validate(row)


def issue(conn: Connection[Any], order: WorkOrder, *, now: datetime) -> str:
    """Write a new order and return the ticket number the sequence gave it.

    The reference is generated by the database rather than built from the machine
    and the time: two orders for one machine inside a minute is unlikely and not
    impossible, and slice 3.0's lesson was what "unlikely" is worth in a primary
    key.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            INSERT INTO work_order ({_COLUMNS}, created_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                    %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING work_order_ref
            """,
            (
                order.origin.value,
                order.finding_ref,
                order.pm_task_ref,
                order.machine_id,
                order.severity.value,
                order.finding_kind.value if order.finding_kind else None,
                order.eta,
                order.eta_confidence,
                order.playbook_ref,
                Jsonb([step.model_dump(mode="json") for step in order.playbook_snapshot]),
                order.snapshot_approved_by,
                order.snapshot_approved_at,
                order.playbook_warning,
                order.estimated_minutes,
                order.required_skill,
                order.required_technicians,
                order.estimate_is_fallback,
                order.reason,
                order.priority_score,
                order.priority_reason,
                order.status.value,
                Jsonb([one.model_dump(mode="json") for one in order.assignees]),
                Jsonb([one.model_dump(mode="json") for one in order.work_segments]),
                order.handover_note,
                order.blocked_minutes,
                [reason.value for reason in order.blocked_reason],
                order.outcome.value if order.outcome else None,
                order.technician_feedback,
                order.reported_by,
                now,
            ),
        )
        row = cur.fetchone()
    assert row is not None
    return str(row["work_order_ref"])


def reported_by(
    conn: Connection[Any], user: UserId, *, limit: int
) -> list[tuple[str, datetime, datetime | None, WorkOrder]]:
    """What this person reported, newest first, whatever became of it (ADR-122)."""
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT work_order_ref, created_at, closed_at, {_COLUMNS} FROM work_order
             WHERE reported_by = %s
             ORDER BY created_at DESC, work_order_ref DESC
             LIMIT %s
            """,
            (user, limit),
        )
        rows = cur.fetchall()
    return [
        (str(row["work_order_ref"]), row["created_at"], row["closed_at"], _to_order(dict(row)))
        for row in rows
    ]


def get(conn: Connection[Any], work_order_ref: str) -> WorkOrder | None:
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"SELECT {_COLUMNS} FROM work_order WHERE work_order_ref = %s",
            (work_order_ref,),
        )
        row = cur.fetchone()
    return _to_order(row) if row else None


def get_for_update(conn: Connection[Any], work_order_ref: str) -> WorkOrder | None:
    """The same read, holding the row until the transaction ends.

    Every transition decides from what it read - which role the next assignee
    takes, whether a slot is free, whether this person already has a segment
    open - and two technicians pressing "accept" on the same ticket at the same
    moment would otherwise both read an unstaffed order and both become primary.
    The lock is cheap: these rows are contended by at most the few people
    standing at one machine.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"SELECT {_COLUMNS} FROM work_order WHERE work_order_ref = %s FOR UPDATE",
            (work_order_ref,),
        )
        row = cur.fetchone()
    return _to_order(row) if row else None


def open_orders(conn: Connection[Any]) -> list[tuple[str, WorkOrder, datetime]]:
    """Everything the dispatch tick has to consider, oldest first.

    The creation time comes back beside the order because the score's waiting
    term needs it and the contract deliberately does not carry it: a `WorkOrder`
    that knew when it was written down could be built without ever having been
    (ADR-045, consequences).

    **No limit, and that is deliberate.** `load_ratio` is a sum over the whole
    queue (design.md 13.2), so a page of it is not a smaller version of the
    answer - it is a shift that reads emptier than it is, and the gate then
    releases *more* work. A truncation that made the queue look manageable would
    do it by hiding the newest orders, including a critical one raised minutes
    ago.

    The bound is the plant's own: open work orders are jobs somebody has to do,
    and a queue long enough for this to matter is a queue that is itself the
    problem to report.

    Ordered by age rather than by severity: ranking is the scheduler's job, and a
    repository that pre-sorted by one term of the score would be quietly deciding
    part of it.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        # The status list is written out rather than passed as an array so the
        # planner can match the partial index in migration 0006. `= ANY($1)`
        # against a generic plan cannot.
        cur.execute(
            f"""
            SELECT work_order_ref, created_at, {_COLUMNS} FROM work_order
             WHERE status IN ('queued', 'proposed', 'assigned', 'in_progress', 'handed_over')
             ORDER BY created_at, work_order_ref
            """
        )
        rows = cur.fetchall()
    return [(str(row["work_order_ref"]), _to_order(dict(row)), row["created_at"]) for row in rows]


def closed_orders(conn: Connection[Any]) -> list[tuple[str, WorkOrder, datetime]]:
    """Every order that has ended, with when it ended, oldest first.

    The history half of a machine's health is built from these (ADR-072 §2), and
    the reduction that health reads - `ClosedRepair` - is not built here:
    `work/` may not import `health/` at all (ADR-072 §4, `.importlinter`). So
    this returns orders and the API composes, exactly as it does for everything
    else it reads from two packages at once.

    `cancelled` is not on the list. A cancelled order is one the world overtook -
    a prediction superseded, a job nobody had started when the Finding resolved
    (ADR-044 §6) - and counting it as history would report a failure the machine
    never finished having. `ClosedRepair.from_order` refuses one anyway; this
    query keeps it from ever being offered.

    No limit, for a narrower version of the reason `open_orders` gives: the
    observed span is computed from the earliest of these, so a page of them is
    not a smaller version of the answer but a shorter window, and every rate
    computed over it would be wrong in the direction that looks alarming.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT work_order_ref, closed_at, {_COLUMNS} FROM work_order
             WHERE status = 'closed' AND closed_at IS NOT NULL
             ORDER BY closed_at, work_order_ref
            """
        )
        rows = cur.fetchall()
    return [(str(row["work_order_ref"]), _to_order(dict(row)), row["closed_at"]) for row in rows]


def assigned_to(conn: Connection[Any], user: UserId) -> list[tuple[str, WorkOrder]]:
    """This person's own live work, in the order layer 3 put it in (ADR-071 §7).

    **Read from the orders rather than from a recomputed round.** The technician's
    screen used to filter `round.placed`, and `dispatch()` considers only orders
    whose status is `queued` - so a job left that list at the instant a round
    wrote it, which is the instant the system decided to give it to somebody. The
    rehearsal could not see it because it stops `worker-runtime` while the screen
    checks run.

    `priority_score` is the copy layer 3 froze onto the order when it placed it,
    so this ordering is the ranking as it was decided and not as it would be
    decided now. That is deliberate (design.md 6.2): a queue that re-ranked on
    every page load would re-order itself under a technician already walking to a
    machine. The reference breaks ties so two jobs scored the same never swap
    places between refreshes, and it is the board's tie-break too: the shift
    lead and the technician see one order (ADR-131).

    `proposed` is absent, and that is the second half of ADR-071 §7: work nobody
    has confirmed is not this person's, and the query that fixes the disappearing
    job is the one that keeps unapproved work off the screen.

    Bounded by the same fact `open_orders` relies on - open work orders are jobs
    somebody has to do - so there is no index on `assignees` and no LIMIT here.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT work_order_ref, {_COLUMNS} FROM work_order
             WHERE status IN ('assigned', 'in_progress', 'handed_over')
               AND assignees @> %s
             ORDER BY priority_score DESC, work_order_ref
            """,
            (Jsonb([{"user": str(user)}]),),
        )
        rows = cur.fetchall()
    return [(str(row["work_order_ref"]), _to_order(dict(row))) for row in rows]


def for_finding(conn: Connection[Any], finding_ref: FindingRef) -> list[tuple[str, WorkOrder]]:
    """What this Finding produced. The trace-back direction (ADR-030)."""
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT work_order_ref, {_COLUMNS} FROM work_order
             WHERE finding_ref = %s ORDER BY created_at
            """,
            (finding_ref,),
        )
        rows = cur.fetchall()
    return [(str(row["work_order_ref"]), _to_order(dict(row))) for row in rows]


def open_for_machine(conn: Connection[Any], machine_id: MachineId) -> list[str]:
    """Open tickets on one machine, for the caller deciding whether to raise
    another. Cheap deliberately: only the references, because the question is
    "is there one" rather than "what does it say"."""
    with conn.cursor() as cur:
        cur.execute(
            # Ordered by the reference as well as the moment, so the list is
            # total. Two orders written in the same instant - which a simulated
            # clock does routinely, and a busy minute does occasionally - would
            # otherwise come back in whatever order the scan found them, and this
            # list is read by a person deciding whether their fault is already
            # known (ADR-077 section 3).
            "SELECT work_order_ref FROM work_order "
            "WHERE machine_id = %s AND status = ANY(%s) ORDER BY created_at, work_order_ref",
            (machine_id, list(OPEN_STATUSES)),
        )
        return [str(row[0]) for row in cur.fetchall()]


class CannotCloseThisWay(Exception):
    """`set_status` was asked to close an order. `close` is the way.

    Closing needs an outcome - the database refuses a closed row without one -
    so a `set_status(CLOSED)` would abort the caller's whole transaction on a
    CHECK constraint rather than doing what it looked like it would do.
    """


def set_status(
    conn: Connection[Any],
    work_order_ref: str,
    *,
    status: WorkOrderStatus,
    handover_note: str | None = None,
) -> bool:
    """Move an order between its open states. Never touches the snapshot.

    Not for closing: an order that has ended has to say how (ADR-022's
    "no problem found" is one of the answers, and the only false-alarm signal
    the system will ever get), and the constraint enforcing that would fail here
    with a message about a CHECK rather than about what the caller forgot.
    """
    if status in (WorkOrderStatus.CLOSED, WorkOrderStatus.CANCELLED):
        raise CannotCloseThisWay(
            f"{status.value} needs an outcome and a time; use close() (ADR-022)"
        )
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET status = %s, handover_note = COALESCE(%s, handover_note)
             WHERE work_order_ref = %s
            """,
            (status.value, handover_note, work_order_ref),
        )
        return cur.rowcount == 1


def add_assignee(conn: Connection[Any], work_order_ref: str, assignee: Assignee) -> bool:
    """Put one person on the order. Nothing else about the row moves.

    The guard is in the statement rather than in the caller: the caller has read
    the row and decided, and between the read and the write is exactly where the
    same person pressing twice on a dropping network lands. Appending is what a
    second press must not do - two entries for one person double the capacity the
    scheduler reserves for the job (ADR-025).
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET assignees = assignees || jsonb_build_array(
                       jsonb_build_object('user', %s::text, 'role', %s::text))
             WHERE work_order_ref = %s
               AND NOT EXISTS (
                   SELECT 1 FROM jsonb_array_elements(assignees) AS one
                    WHERE one->>'user' = %s)
            """,
            (str(assignee.user), assignee.role.value, work_order_ref, str(assignee.user)),
        )
        return cur.rowcount == 1


def remove_assignee(conn: Connection[Any], work_order_ref: str, user: UserId) -> bool:
    """Take one person off the order (ADR-056).

    What they did stays in `work_segments`. `assignees` answers who holds the job
    now, and a technician who has handed it over and gone home does not - layer 3
    subtracts an order's minutes from every assignee of a `handed_over` order, so
    a name left here is capacity nobody can spend and nothing reports.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET assignees = COALESCE((
                       SELECT jsonb_agg(one ORDER BY ord)
                         FROM jsonb_array_elements(assignees) WITH ORDINALITY AS t(one, ord)
                        WHERE one->>'user' <> %s), '[]'::jsonb)
             WHERE work_order_ref = %s
            """,
            (str(user), work_order_ref),
        )
        return cur.rowcount == 1


def open_segment(
    conn: Connection[Any], work_order_ref: str, *, user: UserId, now: datetime
) -> bool:
    """Start one person working. At most one open segment per (order, user).

    False means they already had one open, which is a second press rather than a
    second stretch of work: a duplicate open segment would be closed twice at the
    end and count the same minutes twice into the estimate Loop 1 learns from.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET work_segments = work_segments || jsonb_build_array(jsonb_build_object(
                       'user', %s::text,
                       'started_at', to_jsonb(%s::timestamptz),
                       'ended_at', NULL))
             WHERE work_order_ref = %s
               AND NOT EXISTS (
                   SELECT 1 FROM jsonb_array_elements(work_segments) AS one
                    WHERE one->>'user' = %s AND one->>'ended_at' IS NULL)
            """,
            (str(user), now, work_order_ref, str(user)),
        )
        return cur.rowcount == 1


def close_segments(
    conn: Connection[Any], work_order_ref: str, *, now: datetime, user: UserId | None = None
) -> bool:
    """Stop the clock on the open segments - one person's, or everybody's.

    `user=None` is what closing an order uses. An open segment contributes zero
    to `actual_minutes` (`WorkSegment.duration`), so one left open at close would
    silently discard the time somebody worked, which is the opposite of what
    ADR-025 moved duration onto the segments for.

    The array is rebuilt in order. `jsonb_agg` without `ORDER BY` is free to
    return the elements in any order, and the order of the segments is the order
    the work happened in.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET work_segments = COALESCE((
                       SELECT jsonb_agg(
                                  CASE WHEN one->>'ended_at' IS NULL
                                        AND (%s::text IS NULL OR one->>'user' = %s::text)
                                       THEN jsonb_set(one, '{ended_at}', to_jsonb(%s::timestamptz))
                                       ELSE one END
                                  ORDER BY ord)
                         FROM jsonb_array_elements(work_segments)
                              WITH ORDINALITY AS t(one, ord)), '[]'::jsonb)
             WHERE work_order_ref = %s
            """,
            (str(user) if user else None, str(user) if user else None, now, work_order_ref),
        )
        return cur.rowcount == 1


def open_finding_refs(conn: Connection[Any]) -> set[FindingRef]:
    """Which Findings still have an open ticket against them.

    Half of what the trigger loop needs to say a machine is under repair
    (ADR-044 §6); the other half is the live Findings themselves. Deliberately
    thin - `open_orders` would deserialise every playbook snapshot in the queue
    to answer a question about references, ten seconds apart, for ever.
    """
    with conn.cursor() as cur:
        cur.execute(
            "SELECT DISTINCT finding_ref FROM work_order "
            "WHERE finding_ref IS NOT NULL AND status = ANY(%s)",
            (list(OPEN_STATUSES),),
        )
        return {FindingRef(str(row[0])) for row in cur.fetchall()}


def finished_finding_refs(conn: Connection[Any], refs: Collection[FindingRef]) -> set[FindingRef]:
    """Which of these Findings have had tickets, and have none open any more.

    A Finding with no ticket at all is not in the answer: that is a Finding
    nobody could price, which the loop reports as `unpriced` (ADR-044), and
    resolving it would turn a gap somebody has to close into a Finding that
    quietly went away (ADR-119).
    """
    if not refs:
        return set()
    with conn.cursor() as cur:
        cur.execute(
            "SELECT finding_ref FROM work_order WHERE finding_ref = ANY(%s) "
            "GROUP BY finding_ref HAVING bool_and(status <> ALL(%s))",
            (list(refs), list(OPEN_STATUSES)),
        )
        return {FindingRef(str(row[0])) for row in cur.fetchall()}


def follow_forecast(
    conn: Connection[Any],
    finding_ref: FindingRef,
    *,
    eta: datetime,
    eta_confidence: timedelta,
) -> list[str]:
    """Carry a re-fitted forecast onto the open orders issued from it (ADR-115).

    Only orders still in play: a closed or cancelled order is a record of what
    was believed when it ended, and ADR-018 does not let history move. The
    `reason` sentence is not touched - it is written once, at issue (ADR-005) -
    so what changes is the ETA a screen reads and the urgency a round ranks by.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET eta = %s, eta_confidence = %s
             WHERE finding_ref = %s
               AND status IN ('queued', 'proposed', 'assigned', 'in_progress', 'handed_over')
             RETURNING work_order_ref
            """,
            (eta, eta_confidence, finding_ref),
        )
        return [str(row[0]) for row in cur.fetchall()]


def cancel_untouched_for_finding(
    conn: Connection[Any], finding_ref: FindingRef, *, now: datetime
) -> list[str]:
    """Withdraw the orders for this Finding that nobody has picked up (ADR-044 §7).

    For the trigger loop, when the Finding behind an order is overtaken - a
    prediction superseded by the detection it foresaw, or expired without the
    crossing happening. Left in the queue, those orders are work for a fault that
    has already been ticketed or never happened, and `load_ratio` is a sum over
    the whole open queue (design.md 13.2).

    `proposed` counts as untouched: it is waiting for the shift lead, and no
    technician holds it (ADR-071). Its pending proposal is closed by the caller,
    which owns layer 3's table.

    **The status condition is in the statement, not in the caller.** Between
    reading an order and cancelling it a technician can accept it, and a check
    made in Python would cancel the ticket in somebody's hand. What is returned
    is what was actually cancelled, so a caller cannot report a withdrawal that
    did not happen - the same correction slice 5.1 had to make to `supersede`.

    No outcome is written. The constraint in migration 0006 requires one only for
    `closed`, and `no_problem_found` here would feed the only false-alarm signal
    Loop 2 will ever have with events no person observed. Why it was cancelled is
    in the Finding this order points at: `expired`, or `superseded` with the
    reference to whatever replaced it.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET status = 'cancelled', closed_at = %s
             WHERE finding_ref = %s AND status IN ('queued', 'proposed')
             RETURNING work_order_ref
            """,
            (now, finding_ref),
        )
        return [str(row[0]) for row in cur.fetchall()]


# ── the PM schedule (ADR-083) ──────────────────────────────────────────────
#
# The definitions come from `plant.yaml` and the state lives here. These four
# functions are the whole of the table's surface: mirror the definitions, read
# them back with their state, ask which tasks already have work in flight, and
# record a completion.


class PmTaskDefinition(NamedTuple):
    """One task as configuration states it, with no state attached.

    A tuple rather than `PmTaskConfig` itself, because `work/` reading the
    configuration schema would put layer 2 on the other side of a module that
    exists to be read by layer 3 (ADR-030). The caller converts; there is one
    caller.
    """

    pm_task_ref: PMTaskRef
    machine_id: MachineId
    symptom_code: SymptomCode
    interval: timedelta


def register_pm_tasks(
    conn: Connection[Any], tasks: Sequence[PmTaskDefinition], *, now: datetime
) -> None:
    """Make the table say what `plant.yaml` says, and keep what only it knows.

    Definitions are overwritten and `last_done_at` is never touched: an operator
    correcting an interval has not undone the maintenance. A task that has left
    the configuration is deleted, so that a schedule somebody removed stops
    producing work; the orders it produced stay where they are, which is why
    there is no foreign key onto this table (migration 0013).
    """
    with conn.cursor() as cur:
        for task in tasks:
            cur.execute(
                """
                INSERT INTO pm_task (pm_task_ref, machine_id, symptom_code,
                                     interval_seconds, last_done_at, registered_at)
                     VALUES (%s, %s, %s, %s, NULL, %s)
                ON CONFLICT (pm_task_ref) DO UPDATE
                        SET machine_id = EXCLUDED.machine_id,
                            symptom_code = EXCLUDED.symptom_code,
                            interval_seconds = EXCLUDED.interval_seconds
                """,
                (
                    str(task.pm_task_ref),
                    str(task.machine_id),
                    str(task.symptom_code),
                    int(task.interval.total_seconds()),
                    now,
                ),
            )
        cur.execute(
            "DELETE FROM pm_task WHERE NOT (pm_task_ref = ANY(%s))",
            ([str(task.pm_task_ref) for task in tasks],),
        )


def pm_tasks(conn: Connection[Any]) -> list[PMTask]:
    """Every registered task, with the date it is due computed rather than stored.

    `due_at` is `last_done_at + interval`, or `registered_at` when nothing has
    ever been recorded. #90 asked for the next occurrence to fall out of the
    interval rather than out of a second column, because two columns that have
    to agree are two columns that will not.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            """
            SELECT pm_task_ref, machine_id, symptom_code, interval_seconds,
                   last_done_at, registered_at
              FROM pm_task
          ORDER BY pm_task_ref
            """
        )
        rows = cur.fetchall()
    return [
        PMTask(
            pm_task_ref=PMTaskRef(str(row["pm_task_ref"])),
            machine_id=MachineId(str(row["machine_id"])),
            symptom_code=SymptomCode(str(row["symptom_code"])),
            interval=timedelta(seconds=int(row["interval_seconds"])),
            due_at=(
                row["last_done_at"] + timedelta(seconds=int(row["interval_seconds"]))
                if row["last_done_at"] is not None
                else row["registered_at"]
            ),
            last_done_at=row["last_done_at"],
        )
        for row in rows
    ]


def pm_refs_with_live_order(conn: Connection[Any]) -> set[PMTaskRef]:
    """The tasks that already have work in flight (ADR-083 section 3).

    The same statuses the unique index in migration 0013 names, read here so the
    scan can skip a task rather than attempt an insert the index would refuse -
    an exception would roll back the whole scan, and one task in flight would
    stop every other task falling due.
    """
    with conn.cursor() as cur:
        cur.execute(
            "SELECT DISTINCT pm_task_ref FROM work_order "
            "WHERE pm_task_ref IS NOT NULL AND status = ANY(%s)",
            (list(OPEN_STATUSES),),
        )
        return {PMTaskRef(str(row[0])) for row in cur.fetchall()}


def record_pm_done(conn: Connection[Any], pm_task_ref: PMTaskRef, *, at: datetime) -> bool:
    """Move the task's clock forward. The next occurrence follows from it.

    Never backwards: a closure being recorded late, or a demo seeding a date, may
    not undo a completion already written. Returns whether anything moved, which
    is how the caller can tell a task it knows about from one that has left the
    configuration since the order was issued.
    """
    with conn.cursor() as cur:
        cur.execute(
            "UPDATE pm_task SET last_done_at = %s "
            "WHERE pm_task_ref = %s AND (last_done_at IS NULL OR last_done_at < %s)",
            (at, str(pm_task_ref), at),
        )
        return cur.rowcount > 0


def close(
    conn: Connection[Any],
    work_order_ref: str,
    *,
    status: WorkOrderStatus,
    outcome: WorkOutcome,
    now: datetime,
    blocked_minutes: int = 0,
    blocked_reason: tuple[BlockedReason, ...] = (),
    technician_feedback: str | None = None,
) -> bool:
    """End an order, with how it ended, what held it up, and when.

    `closed_at` comes from the clock the caller passes, never `now()`: a
    compressed demo would otherwise stamp real time on a job whose segments are
    simulated (ADR-028).

    The blocked figures are written here rather than through `set_status`,
    because they are part of how the job ended and are what
    `WorkOrder.repair_minutes` subtracts. Waiting for a part is not repair time,
    and left in it inflates the estimate for that symptom every cycle until
    `load_ratio` reads every shift as full (ADR-006, ADR-025).
    """
    if status not in (WorkOrderStatus.CLOSED, WorkOrderStatus.CANCELLED):
        raise ValueError(f"{status.value} is not an ending; use set_status()")
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order
               SET status = %s, outcome = %s, closed_at = %s,
                   blocked_minutes = %s, blocked_reason = %s,
                   technician_feedback = COALESCE(%s, technician_feedback)
             WHERE work_order_ref = %s
            """,
            (
                status.value,
                outcome.value,
                now,
                blocked_minutes,
                [reason.value for reason in blocked_reason],
                technician_feedback,
                work_order_ref,
            ),
        )
        return cur.rowcount == 1


def closed_since(conn: Connection[Any], since: datetime) -> list[tuple[str, datetime, WorkOrder]]:
    """Orders closed at or after `since`, newest first (ADR-126)."""
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT work_order_ref, closed_at, {_COLUMNS} FROM work_order
             WHERE status = 'closed' AND closed_at >= %s
             ORDER BY closed_at DESC, work_order_ref DESC
            """,
            (since,),
        )
        rows = cur.fetchall()
    return [(str(row["work_order_ref"]), row["closed_at"], _to_order(dict(row))) for row in rows]


def notes_from_the_floor(conn: Connection[Any], *, limit: int) -> list[dict[str, Any]]:
    """The notes technicians wrote when they closed a job, newest first (ADR-117).

    `technician_feedback` was written at every close and read by nothing, so a
    technician telling the engineer "step 3 needs a 13 mm socket, not 10" said it
    to nobody. The symptom is taken from whatever the order came from - its
    Finding, its PM task, or the playbook it was priced from - so a note can be
    read beside the procedure it is about.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            """
            SELECT o.work_order_ref, o.machine_id, o.playbook_ref, o.outcome,
                   o.closed_at, btrim(o.technician_feedback) AS note,
                   COALESCE(f.symptom_code, p.symptom_code,
                            NULLIF(split_part(o.playbook_ref, '/', 1), '')) AS symptom_code
              FROM work_order o
              LEFT JOIN finding f ON f.finding_ref = o.finding_ref
              LEFT JOIN pm_task p ON p.pm_task_ref = o.pm_task_ref
             WHERE o.status = 'closed'
               AND o.technician_feedback IS NOT NULL
               AND btrim(o.technician_feedback) <> ''
             ORDER BY o.closed_at DESC, o.work_order_ref
             LIMIT %s
            """,
            (limit,),
        )
        return list(cur.fetchall())


def closed_jobs_for(conn: Connection[Any], *, playbook_ref: str) -> list[ClosedJob]:
    """Every closed order that was priced from one playbook, as evidence.

    Joined to `finding` for the rule that raised it and for nothing else: the
    rule is what a false alarm is a false alarm *of* (ADR-022). The join is left,
    because scheduled and manual work has no Finding and dropping it would hide
    the false alarms nobody's rule produced.

    `repair_minutes` is not computed in SQL. It is `WorkOrder.repair_minutes`,
    read off the reconstructed order, so the subtraction of blocked time has one
    definition in this system rather than one here and one in the contract
    (ADR-025).
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            f"""
            SELECT o.work_order_ref, f.rule_id, {_COLUMNS_FOR_JOIN}
              FROM work_order o
              LEFT JOIN finding f ON f.finding_ref = o.finding_ref
             WHERE o.status = 'closed' AND o.playbook_ref = %s
             ORDER BY o.created_at, o.work_order_ref
            """,
            (playbook_ref,),
        )
        rows = cur.fetchall()

    jobs = []
    for row in rows:
        work_order_ref = WorkOrderRef(str(row["work_order_ref"]))
        rule = row.pop("rule_id")
        jobs.append(
            ClosedJob.from_order(
                work_order_ref,
                _to_order(row),
                rule_id=RuleId(str(rule)) if rule is not None else None,
            )
        )
    return jobs


def false_alarms(conn: Connection[Any]) -> list[FalseAlarmCount]:
    """How much of the closed work turned out to be nothing, per rule and symptom.

    Counted here rather than in `triggers/`, where the rules live: the outcome is
    on the work order, and a layer-1 module querying layer 2's table to find out
    what happened to its own Findings is the coupling ADR-030 spends the
    `machine_id` copy to avoid.

    Ordered by count, because the question this answers is "which rule is sending
    people out for nothing", and the answer is read from the top (ADR-060 orders
    the authoring queue on the same argument).
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            """
            SELECT f.symptom_code, f.rule_id, count(*) AS orders
              FROM work_order o
              LEFT JOIN finding f ON f.finding_ref = o.finding_ref
             WHERE o.status = 'closed' AND o.outcome = 'no_problem_found'
             GROUP BY f.symptom_code, f.rule_id
             ORDER BY orders DESC, f.symptom_code NULLS LAST, f.rule_id NULLS LAST
            """
        )
        return [
            FalseAlarmCount(
                symptom_code=(
                    SymptomCode(str(row["symptom_code"])) if row["symptom_code"] else None
                ),
                rule_id=RuleId(str(row["rule_id"])) if row["rule_id"] else None,
                orders=int(row["orders"]),
            )
            for row in cur.fetchall()
        ]


def firings_behind_rules(conn: Connection[Any]) -> list[RuleFirings]:
    """The closed work behind every rule, with the reading each one fired on.

    Loop 2's evidence (ADR-073). Read here rather than in `triggers/` for the
    reason `false_alarms` is: the outcome lives on the work order, and a layer-1
    module querying layer 2's table to find out what happened to its own Findings
    is the coupling ADR-030 spends the `machine_id` copy to avoid.

    **One row per closed order, never per occurrence.** ADR-023's suppression key
    makes one Finding stand for an unbroken run of breaching samples, so a sensor
    that flapped forty times is one Finding, one order and one observation here.
    Counting `occurrence_count` would let that one sensor supply an entire
    evidence set while the proposal read as though forty jobs supported it
    (ADR-073 section 2).

    A Finding whose evidence recorded no numeric reading is counted rather than
    dropped: it is a gap in what layer 1 wrote down, and a set that quietly shrank
    would look like a rule with less history than it has.
    """
    with conn.cursor(row_factory=dict_row) as cur:
        cur.execute(
            """
            SELECT o.work_order_ref, o.outcome, f.rule_id, f.kind,
                   f.evidence -> 'value' AS reading
              FROM work_order o
              JOIN finding f ON f.finding_ref = o.finding_ref
             WHERE o.status = 'closed' AND o.outcome IS NOT NULL
             ORDER BY f.rule_id, o.work_order_ref
            """
        )
        rows = cur.fetchall()

    firings: dict[RuleId, list[RuleFiring]] = {}
    missing: dict[RuleId, int] = {}
    for row in rows:
        rule_id = RuleId(str(row["rule_id"]))
        firings.setdefault(rule_id, [])
        missing.setdefault(rule_id, 0)
        reading = row["reading"]
        if not isinstance(reading, int | float) or isinstance(reading, bool):
            missing[rule_id] += 1
            continue
        firings[rule_id].append(
            RuleFiring(
                work_order_ref=WorkOrderRef(str(row["work_order_ref"])),
                outcome=WorkOutcome(str(row["outcome"])),
                value=float(reading),
                finding_kind=FindingKind(str(row["kind"])),
            )
        )

    return [
        RuleFirings(
            rule_id=rule_id,
            firings=tuple(firings[rule_id]),
            without_a_reading=missing[rule_id],
        )
        for rule_id in sorted(firings)
    ]


def adopt_playbook(
    conn: Connection[Any],
    playbook: Playbook,
    *,
    machine_ids: Sequence[str],
) -> list[str]:
    """Give a newly approved playbook to the orders that were waiting for one.

    ADR-102: an order issued before any playbook existed for its symptom carries
    no steps, and nothing else will ever bring them - the Finding stays open, so
    no new order is issued. Only orders with **no steps and no work segment**
    adopt it, still queued, proposed or assigned; the migration 0015 trigger
    allows that one change and nothing else, and the conditions are in the
    statement so that a technician starting the job at the same moment wins.

    Matched by symptom through the Finding (condition orders) or the PM task
    (scheduled orders), on this playbook's machines. Reported faults name no
    symptom, so they are left to the engineer.
    """
    steps = Jsonb([step.model_dump(mode="json") for step in playbook.steps])
    with conn.cursor() as cur:
        cur.execute(
            """
            UPDATE work_order AS wo
               SET playbook_ref = %(ref)s,
                   playbook_snapshot = %(steps)s,
                   snapshot_approved_by = %(by)s,
                   snapshot_approved_at = %(at)s,
                   playbook_warning = NULL,
                   estimated_minutes = %(minutes)s,
                   estimate_is_fallback = false,
                   required_skill = %(skill)s,
                   required_technicians = %(technicians)s
             WHERE wo.status IN ('queued', 'proposed', 'assigned')
               AND wo.playbook_snapshot = '[]'::jsonb
               AND wo.work_segments = '[]'::jsonb
               AND wo.machine_id = ANY(%(machines)s)
               AND (
                    EXISTS (SELECT 1 FROM finding f
                             WHERE f.finding_ref = wo.finding_ref
                               AND f.symptom_code = %(symptom)s)
                 OR EXISTS (SELECT 1 FROM pm_task t
                             WHERE t.pm_task_ref = wo.pm_task_ref
                               AND t.symptom_code = %(symptom)s)
               )
            RETURNING wo.work_order_ref
            """,
            {
                "ref": f"{playbook.symptom_code}/{playbook.machine_model}",
                "steps": steps,
                "by": playbook.approved_by,
                "at": playbook.approved_at,
                "minutes": playbook.estimated_minutes,
                "skill": playbook.required_skill,
                "technicians": playbook.required_technicians,
                "machines": list(machine_ids),
                "symptom": playbook.symptom_code,
            },
        )
        return [row[0] for row in cur.fetchall()]
